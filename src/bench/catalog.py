"""Write docs/tasks.md: the task catalogue, generated from the task specs.

bench catalog
"""

from __future__ import annotations

from collections import Counter

from bench.constants import CANARY
from bench.patches import accepted_fix_patches, wrong_fix_patches
from bench.paths import ROOT
from bench.spec import CATEGORIES, CATEGORY_PRINCIPLES, CHANNELS, TaskSpec, load_specs


def _row(s: TaskSpec) -> str:
    m = s.metadata
    return (
        f"| `{s.id}` | {m.category} | {m.channel} | {m.family} | {m.difficulty} | {m.fault_kind} | "
        f"{m.provenance_kind} | {len(wrong_fix_patches(s))} | {len(accepted_fix_patches(s))} | {m.principle} |"
    )


def main(argv: list[str] | None = None) -> None:
    specs = load_specs()
    test = [s for s in specs if s.split == "test"]
    dev = [s for s in specs if s.split == "dev"]
    by_cat = Counter(s.metadata.category for s in test)
    by_channel = Counter(s.metadata.channel for s in test)
    kinds = Counter(s.metadata.provenance_kind for s in test)
    covered = sum(bool(wrong_fix_patches(s)) for s in test)
    lines = [
        "# Task catalogue",
        "",
        f"<!-- {CANARY} -->",
        "",
        "Generated by `bench catalog` from `families/*/*/spec.yaml`.",
        "",
        f"Test tasks: {len(test)}. Dev tasks: {len(dev)}. Provenance: "
        + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items()))
        + f". Test tasks with scripted wrong fixes: {covered}/{len(test)}.",
        "",
        "| Category | Test tasks | Principle |",
        "|---|---|---|",
    ]
    lines += [f"| {c} | {by_cat.get(c, 0)} | {CATEGORY_PRINCIPLES[c]} |" for c in CATEGORIES]
    lines += ["", "Deciding evidence channel (no channel may exceed a fifth of the test split):", "",
              "| Channel | Test tasks |", "|---|---|"]  # fmt: skip
    lines += [f"| {c} | {by_channel.get(c, 0)} |" for c in CHANNELS]
    for split, group in (("Test", test), ("Dev", dev)):
        lines += [
            "",
            f"## {split} tasks",
            "",
            "| Task | Category | Channel | Family | Difficulty (author) | Fault | Provenance | Wrong fixes "
            "| Accepted fixes | Principle |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        lines += [_row(s) for s in sorted(group, key=lambda s: (CATEGORIES.index(s.metadata.category), s.id))]
    (ROOT / "docs" / "tasks.md").write_text("\n".join(lines) + "\n")
    print(f"wrote docs/tasks.md ({len(test)} test, {len(dev)} dev)")


if __name__ == "__main__":
    main()
